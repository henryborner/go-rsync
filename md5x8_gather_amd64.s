// md5x8_gather_amd64.s — VPGATHERDD-based 8-block load+transpose.
// Replaces the ~288-instruction scalar path in md5x8LoadTranspose
// with ~32 gather-based operations per 64-byte chunk.

#include "textflag.h"

// func md5x8LoadTransposeGather(data []byte, offsets *[8]int, chunk int, x *[16][8]uint32)
TEXT ·md5x8LoadTransposeGather(SB), NOSPLIT, $0-48
	MOVQ data+0(FP), R8       // data base
	MOVQ offsets+24(FP), R9    // &offsets[0]
	MOVQ chunk+32(FP), R10     // chunk index
	MOVQ x+40(FP), R11         // x output pointer

	// CX = chunk * 64
	MOVQ R10, CX
	SHLQ $6, CX

	// Build Y0 = 8 int32 indices: offsets[b] + chunk*64  (without data base)
	// We compute each as 32-bit value and pack into Y0 (lower 128) + Y1 (upper 128)
	MOVQ (R9), R12; ADDQ CX, R12; VMOVD R12, X0
	MOVQ 8(R9), R13; ADDQ CX, R13; VPINSRD $1, R13, X0, X0
	MOVQ 16(R9), R14; ADDQ CX, R14; VPINSRD $2, R14, X0, X0
	MOVQ 24(R9), R15; ADDQ CX, R15; VPINSRD $3, R15, X0, X0
	MOVQ 32(R9), AX;  ADDQ CX, AX;  VMOVD AX, X1
	MOVQ 40(R9), BX;  ADDQ CX, BX;  VPINSRD $1, BX, X1, X1
	MOVQ 48(R9), DX;  ADDQ CX, DX;  VPINSRD $2, DX, X1, X1
	MOVQ 56(R9), DI;  ADDQ CX, DI;  VPINSRD $3, DI, X1, X1
	VINSERTI128 $1, X1, Y0, Y0     // Y0 = 8 indices (byte offsets from data start)

	// Y1 = all-ones mask for full gather
	VPCMPEQD Y2, Y2, Y1

	// Y3 = broadcast constant for word offset increments
	// We'll use VPADDD to add {w*4, w*4, ...} to Y0 for each word w

	// Pre-compute 16 gathered YMM words into x[0..15]
	// Word 0: Y0 has base indices; gather directly
	VPGATHERDD Y1, (R8)(Y0*1), Y4
	VMOVDQU Y4, 0(R11)

	// Word 1: VPADDD Y0 with {4,4,4,4,4,4,4,4}, then gather
	VMOVDQU WORD4<>(SB), Y3
	VPADDD Y0, Y3, Y2
	VPGATHERDD Y1, (R8)(Y2*1), Y4
	VMOVDQU Y4, 32(R11)

	// Word 2: offset += 8
	VMOVDQU WORD8<>(SB), Y3
	VPADDD Y0, Y3, Y2
	VPGATHERDD Y1, (R8)(Y2*1), Y4
	VMOVDQU Y4, 64(R11)

	// Word 3: offset += 12
	VMOVDQU WORD12<>(SB), Y3
	VPADDD Y0, Y3, Y2
	VPGATHERDD Y1, (R8)(Y2*1), Y4
	VMOVDQU Y4, 96(R11)

	// Word 4: offset += 16
	VMOVDQU WORD16<>(SB), Y3
	VPADDD Y0, Y3, Y2
	VPGATHERDD Y1, (R8)(Y2*1), Y4
	VMOVDQU Y4, 128(R11)

	// Word 5: offset += 20
	VMOVDQU WORD20<>(SB), Y3
	VPADDD Y0, Y3, Y2
	VPGATHERDD Y1, (R8)(Y2*1), Y4
	VMOVDQU Y4, 160(R11)

	// Word 6: offset += 24
	VMOVDQU WORD24<>(SB), Y3
	VPADDD Y0, Y3, Y2
	VPGATHERDD Y1, (R8)(Y2*1), Y4
	VMOVDQU Y4, 192(R11)

	// Word 7: offset += 28
	VMOVDQU WORD28<>(SB), Y3
	VPADDD Y0, Y3, Y2
	VPGATHERDD Y1, (R8)(Y2*1), Y4
	VMOVDQU Y4, 224(R11)

	// Word 8: offset += 32
	VMOVDQU WORD32<>(SB), Y3
	VPADDD Y0, Y3, Y2
	VPGATHERDD Y1, (R8)(Y2*1), Y4
	VMOVDQU Y4, 256(R11)

	// Word 9: offset += 36
	VMOVDQU WORD36<>(SB), Y3
	VPADDD Y0, Y3, Y2
	VPGATHERDD Y1, (R8)(Y2*1), Y4
	VMOVDQU Y4, 288(R11)

	// Word 10: offset += 40
	VMOVDQU WORD40<>(SB), Y3
	VPADDD Y0, Y3, Y2
	VPGATHERDD Y1, (R8)(Y2*1), Y4
	VMOVDQU Y4, 320(R11)

	// Word 11: offset += 44
	VMOVDQU WORD44<>(SB), Y3
	VPADDD Y0, Y3, Y2
	VPGATHERDD Y1, (R8)(Y2*1), Y4
	VMOVDQU Y4, 352(R11)

	// Word 12: offset += 48
	VMOVDQU WORD48<>(SB), Y3
	VPADDD Y0, Y3, Y2
	VPGATHERDD Y1, (R8)(Y2*1), Y4
	VMOVDQU Y4, 384(R11)

	// Word 13: offset += 52
	VMOVDQU WORD52<>(SB), Y3
	VPADDD Y0, Y3, Y2
	VPGATHERDD Y1, (R8)(Y2*1), Y4
	VMOVDQU Y4, 416(R11)

	// Word 14: offset += 56
	VMOVDQU WORD56<>(SB), Y3
	VPADDD Y0, Y3, Y2
	VPGATHERDD Y1, (R8)(Y2*1), Y4
	VMOVDQU Y4, 448(R11)

	// Word 15: offset += 60
	VMOVDQU WORD60<>(SB), Y3
	VPADDD Y0, Y3, Y2
	VPGATHERDD Y1, (R8)(Y2*1), Y4
	VMOVDQU Y4, 480(R11)

	VZEROUPPER
	RET

