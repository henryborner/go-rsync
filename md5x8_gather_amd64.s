// md5x8_gather_amd64.s — VPGATHERDD via raw machine code.
// NOTE: VPGATHERDD zeros the mask after execution — must reload before each gather.

#include "textflag.h"

// func md5x8LoadTransposeGather(data []byte, offsets *[8]int, chunk int, x *[16][8]uint32)
TEXT ·md5x8LoadTransposeGather(SB), NOSPLIT, $0-48
	MOVQ data+0(FP), R8
	MOVQ offsets+24(FP), R9
	MOVQ chunk+32(FP), R10
	MOVQ x+40(FP), R11

	MOVQ R10, CX; SHLQ $6, CX

	// Build Y7 = word offsets
	MOVQ (R9), R12; ADDQ CX, R12; SHRQ $1, R12; VMOVD R12, X0
	MOVQ 8(R9), R13; ADDQ CX, R13; SHRQ $1, R13; VPINSRD $1, R13, X0, X0
	MOVQ 16(R9), R14; ADDQ CX, R14; SHRQ $1, R14; VPINSRD $2, R14, X0, X0
	MOVQ 24(R9), R15; ADDQ CX, R15; SHRQ $1, R15; VPINSRD $3, R15, X0, X0
	MOVQ 32(R9), AX;  ADDQ CX, AX;  SHRQ $1, AX;  VMOVD AX, X1
	MOVQ 40(R9), BX;  ADDQ CX, BX;  SHRQ $1, BX;  VPINSRD $1, BX, X1, X1
	MOVQ 48(R9), DX;  ADDQ CX, DX;  SHRQ $1, DX;  VPINSRD $2, DX, X1, X1
	MOVQ 56(R9), DI;  ADDQ CX, DI;  SHRQ $1, DI;  VPINSRD $3, DI, X1, X1
	VINSERTI128 $1, X1, Y0, Y0
	VMOVDQU Y0, Y7

	// Y3 = all-ones mask (pre-compute once, VPGATHERDD zeros the mask each time)
	VPCMPEQD Y3, Y3, Y3

	// Word 0: reload mask to Y2, then gather
	VMOVDQA Y3, Y2
	BYTE $0xC4; BYTE $0xC2; BYTE $0x6D; BYTE $0x90; BYTE $0x0C; BYTE $0x78
	VMOVDQU Y1, 0(R11)

	VMOVDQA Y3, Y2; BYTE $0xC4; BYTE $0xC2; BYTE $0x6D; BYTE $0x90; BYTE $0x4C; BYTE $0x78; BYTE $0x04
	VMOVDQU Y1, 32(R11)
	VMOVDQA Y3, Y2; BYTE $0xC4; BYTE $0xC2; BYTE $0x6D; BYTE $0x90; BYTE $0x4C; BYTE $0x78; BYTE $0x08
	VMOVDQU Y1, 64(R11)
	VMOVDQA Y3, Y2; BYTE $0xC4; BYTE $0xC2; BYTE $0x6D; BYTE $0x90; BYTE $0x4C; BYTE $0x78; BYTE $0x0C
	VMOVDQU Y1, 96(R11)
	VMOVDQA Y3, Y2; BYTE $0xC4; BYTE $0xC2; BYTE $0x6D; BYTE $0x90; BYTE $0x4C; BYTE $0x78; BYTE $0x10
	VMOVDQU Y1, 128(R11)
